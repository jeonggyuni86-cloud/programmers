
// 다형성 - 업 캐스팅, 동적 바인딩, is/as

// 다형성은 "부모 타입 하나로 여러 자식을 똑같이 다루는 것"이다.
// 부르는 쪽은 무엇인지 몰라도 되고, 실제로는 각 객체에 맞는 동작이 실행된다.

// 1. 업캐스팅 - 자식 객체를 부모 타입에 담기
